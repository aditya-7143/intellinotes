from typing import Optional, Protocol
from uuid import UUID

from app.domain.models import Folder, Note, ProposalStatus, StructuringProposal, User


class UserRepository(Protocol):
    async def create(self, user: User) -> User: ...
    async def get_by_id(self, user_id: UUID) -> Optional[User]: ...
    async def get_by_email(self, email: str) -> Optional[User]: ...
    async def update(self, user: User) -> User: ...
    async def delete(self, user_id: UUID) -> bool: ...


class FolderRepository(Protocol):
    async def get_paths(self, user_id: UUID) -> list[str]: ...
    async def create(self, folder: Folder) -> Folder: ...
    async def get_by_user(self, user_id: UUID) -> list[Folder]: ...
    async def get_by_path(self, user_id: UUID, path: str) -> Optional[Folder]: ...
    async def move(self, user_id: UUID, path: str, destination: str) -> Folder: ...
    async def delete(self, user_id: UUID, path: str) -> bool: ...


class NoteRepository(Protocol):
    async def create(self, note: Note) -> Note: ...
    async def get_by_id(self, note_id: UUID, for_update: bool = False) -> Optional[Note]: ...
    async def get_by_user(self, user_id: UUID, folder_path: Optional[str] = None) -> list[Note]: ...
    async def get_by_storage_key(self, storage_key: str) -> Optional[Note]: ...
    async def update(self, note: Note) -> Note: ...
    async def delete(self, note_id: UUID) -> bool: ...
    async def search(self, user_id: UUID, query: str) -> list[Note]: ...


class ProposalRepository(Protocol):
    async def create(self, proposal: StructuringProposal) -> StructuringProposal: ...
    async def get_by_id(
        self, proposal_id: UUID, for_update: bool = False
    ) -> Optional[StructuringProposal]: ...
    async def get_by_user(
        self, user_id: UUID, status: Optional[ProposalStatus] = None
    ) -> list[StructuringProposal]: ...
    async def update(self, proposal: StructuringProposal) -> StructuringProposal: ...
    async def delete(self, proposal_id: UUID) -> bool: ...


class LLMProvider(Protocol):
    async def structure_notes(self, snippet: str, context: Optional[str] = None) -> dict: ...


class StorageRepository(Protocol):
    async def save(self, key: str, content: bytes) -> str: ...
    async def get(self, key: str) -> Optional[bytes]: ...
    async def delete(self, key: str) -> bool: ...
    async def exists(self, key: str) -> bool: ...
    async def list_keys(self, prefix: str) -> list[str]: ...
    async def list_folders(self, prefix: str) -> list[str]: ...
    async def create_folder(self, key: str) -> None: ...
    async def move_folder(self, key: str, destination: str) -> None: ...
    async def delete_folder(self, key: str) -> bool: ...


class AcceptanceTransaction(Protocol):
    async def lock_user(self, user_id: UUID) -> None: ...
    async def save(self, key: str, content: bytes, expected: bytes | None) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
